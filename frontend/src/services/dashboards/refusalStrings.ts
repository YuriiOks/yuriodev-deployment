/**
 * What a refusal by the server is told as: the page's own words for each code it sends (never the server's own text), for a bad line of a
 * statement, and for each broken rule of a field (`issues` of a 422), under the field's own name.
 */
export interface RefusalStrings {
  /** By the family code of the refusal (`error`) or its finer one (`reason`); a code that is not here is told as the generic failure by the caller. */
  readonly codes: Readonly<Record<string, string>>;
  /** A broken rule of one field, by the issue's code (`out_of_range` is told by its bound: `out_of_range_min` or `out_of_range_max`); {limit} is the number that was broken. */
  readonly issues: Readonly<Record<string, string>>;
  /** A statement line that could not be read, and the fields by the server's name for them. */
  readonly line: string;
  readonly fields: Readonly<Record<string, string>>;
}

